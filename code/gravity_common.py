def member(span: dict, iso: str, year: int) -> int:
    """1, если страна iso в год year входит в объединение со сроками span."""
    if iso not in span:
        return 0
    a, b = span[iso]
    return int(a <= year <= b)


def both_members(span: dict, iso_i: str, iso_j: str, year: int) -> int:
    return member(span, iso_i, year) * member(span, iso_j, year)


def partner_group(iso_partner: str) -> str:
    """Группа партнёра России: coalition / ukraine / other."""
    if iso_partner in COALITION_2022:
        return "coalition"
    if iso_partner == UKRAINE:
        return "ukraine"
    return "other"
